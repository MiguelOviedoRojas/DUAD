CREATE TABLE IF NOT EXISTS USERS (
	ID INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	DNI VARCHAR(20) UNIQUE NOT NULL,
	NAME VARCHAR(25) NOT NULL,
	EMAIL VARCHAR(50) NOT NULL,
	PHONE VARCHAR(25) NOT NULL,
	ADDRESS VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS PRODUCTS(
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	DESCRIPTION VARCHAR(30) NOT NULL,
	PRICE NUMERIC(10,2) NOT NULL CHECK (PRICE > 0),
	STOCK INTEGER DEFAULT 0 CHECK (STOCK >= 0),
	BRAND VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS BILLS(
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	BILL_DATE DATE DEFAULT CURRENT_DATE,
	STATE VARCHAR(15) NOT NULL DEFAULT 'ACTIVE' CHECK (STATE IN ('PENDING', 'ACTIVE', 'RETURNED')),
	ID_USER INTEGER NOT NULL REFERENCES USERS(ID)
);

CREATE TABLE IF NOT EXISTS BILLS_DETAILS(
	ID INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ID_BILL INTEGER NOT NULL REFERENCES BILLS(ID),
	ID_PRODUCT INTEGER NOT NULL REFERENCES PRODUCTS(ID),
	QUANTITY INTEGER NOT NULL CHECK (QUANTITY > 0),
	UNIT_PRICE NUMERIC(10,2) NOT NULL CHECK (UNIT_PRICE > 0)
);